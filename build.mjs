/*
 * Build the shipped client bundle from src/copy-markdown.js.
 *
 * The DSH client loads `client.js` as a plain script through
 * window.__ModuleLoader__, so the serializer is inlined here instead of being
 * imported at runtime.  Run `node build.mjs` after editing the source.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const packageName = JSON.parse(readFileSync(join(root, "package.json"), "utf8")).name;
const source = readFileSync(join(root, "src", "copy-markdown.js"), "utf8");

const indented = source
  .replace(/\s+$/, "")
  .split("\n")
  .map((line) => (line ? "    " + line : ""))
  .join("\n");

const wrapper = `/* Generated by build.mjs from src/copy-markdown.js — do not edit by hand. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(packageName)},
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
    "use strict";

${indented}

    /* -- selection copy handler ------------------------------------------ */

    function elementOf(node) {
      if (!node) return null;
      return node.nodeType === 1 ? node : node.parentElement || null;
    }

    function isEditable(node) {
      var element = elementOf(node);
      if (!element || typeof element.closest !== "function") return false;
      return element.closest(
        "input, textarea, select, [contenteditable=''], [contenteditable='true']"
      ) !== null;
    }

    function findChatFlow(node) {
      var flows = document.querySelectorAll("[data-chat-flow]");
      for (var i = 0; i < flows.length; i += 1) {
        if (flows[i].contains(node)) return flows[i];
      }
      return null;
    }

    function onCopy(event) {
      try {
        var selection = document.getSelection();
        if (!selection || selection.isCollapsed || selection.rangeCount === 0) return;
        var range = selection.getRangeAt(0);
        if (isEditable(range.startContainer) || isEditable(range.endContainer)) return;
        var flow = findChatFlow(range.startContainer);
        if (!flow || !flow.contains(range.endContainer)) return;
        var markdown = serializeSelectionMarkdown(range);
        if (!markdown || !markdown.trim()) return;
        if (!event.clipboardData) return;
        event.clipboardData.setData("text/plain", markdown);
        event.preventDefault();
      } catch (error) {
        /* Keep the browser's own copy behavior when conversion fails. */
        console.error("[dsh-markdown-copy] failed to convert the selection", error);
      }
    }

    function apply(ctx) {
      ctx.effect(
        () => {
          document.addEventListener("copy", onCopy, true);
          return () => document.removeEventListener("copy", onCopy, true);
        },
        "dsh-markdown-copy: copy selection as Markdown"
      );
    }

    var inject = [];
    exports.apply = apply;
    exports.inject = inject;
    return module.exports;
  }
});
`;

writeFileSync(join(root, "client.js"), wrapper);
console.log(`wrote client.js (${packageName})`);
